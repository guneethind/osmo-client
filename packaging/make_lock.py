"""Writes packaging/requirements-windows.lock: every package the Windows build installs, pinned to one version
and one file hash (the Windows, Python 3.14 wheel), so the release is built from exactly the files that were
checked here and a changed upstream file fails the build instead of slipping in.

Run it (on Windows, with Python 3.14) when requirements.txt or requirements-windows.in changes, then commit:
    python packaging/make_lock.py
"""

import json
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main() -> None:
    with tempfile.TemporaryDirectory() as folder:
        report = Path(folder) / "report.json"
        subprocess.run([sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet",
                        "--only-binary=:all:", "--timeout", "120", "--retries", "8", "--report", str(report),
                        "-r", str(HERE / "requirements-windows.in")], check=True)
        installs = json.loads(report.read_text(encoding="utf-8"))["install"]
    lines = ["# Generated by packaging/make_lock.py from requirements-windows.in. Do not edit by hand.",
             f"# Python {sys.version_info.major}.{sys.version_info.minor}, Windows x64."]
    for item in sorted(installs, key=lambda i: i["metadata"]["name"].lower()):
        sha256 = item["download_info"]["archive_info"]["hashes"]["sha256"]
        lines.append(f"{item['metadata']['name']}=={item['metadata']['version']} \\")
        lines.append(f"    --hash=sha256:{sha256}")
    (HERE / "requirements-windows.lock").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(installs)} packages pinned")


if __name__ == "__main__":
    main()
